/** Locally administered addresses are randomized by the device, not a vendor. */
export function isLocallyAdministered(mac: string): boolean {
  const firstOctet = parseInt(mac.slice(0, 2), 16)
  return Number.isFinite(firstOctet) && (firstOctet & 0x02) !== 0
}

export function lookupVendor(mac: string | null): string | null {
  if (!mac) return null
  const hex = mac.replace(/[^0-9A-Fa-f]/g, '').toUpperCase()
  if (hex.length < 6) return null
  if (isLocallyAdministered(hex)) return 'Randomized MAC (private address)'
  return OUI[hex.slice(0, 6)] ?? null
}
